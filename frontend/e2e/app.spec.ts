import { test, expect, type Page } from '@playwright/test'

const shot = (page: Page, name: string) => page.screenshot({ path: `e2e-results/screens/${name}.png`, fullPage: false })

test.describe('GridRescue AI — end-to-end', () => {
  test('home → explorer → facility → assessment → all result pages', async ({ page }) => {
    // ── Home ─────────────────────────────────────────────────────────────
    await page.goto('/')
    await expect(page).toHaveTitle(/GridRescue AI/)
    await expect(page.getByTestId('kpis')).toBeVisible()
    await expect(page.getByTestId('backend-status')).toContainText(/API/)
    // one screen: the home page must not scroll
    expect(await page.evaluate(() => document.documentElement.scrollHeight <= window.innerHeight + 1)).toBe(true)
    await expect(page.getByTestId('three-as')).toContainText(/Affordability/)
    await expect(page.getByTestId('steps')).toContainText(/Scan the grid/)
    await shot(page, '01-home')
    await page.getByTestId('three-as').scrollIntoViewIfNeeded()
    await shot(page, '01b-home-three-as')
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.getByTestId('cta-explore').click()

    // ── Explorer ─────────────────────────────────────────────────────────
    await expect(page).toHaveURL(/\/explorer/)
    await expect(page.getByTestId('map')).toBeVisible()
    await expect(page.locator('.leaflet-container')).toBeVisible()
    await expect(page.getByTestId('lens-sun')).toBeVisible()
    await expect(page.getByTestId('place-name')).not.toHaveText(/Resolving|^$/, { timeout: 20000 })
    await expect(page.getByTestId('track-peak')).toBeVisible()
    await shot(page, '02-explorer-sun')

    await page.getByTestId('mode-wind').click()
    await expect(page.getByTestId('lens-wind')).toBeVisible()
    await expect(page.getByTestId('track-wind')).toBeVisible()
    await shot(page, '03-explorer-wind')

    // month chips
    const chips = page.getByTestId('month-grid').locator('button')
    await chips.nth(7).click()
    await expect(chips.nth(7)).toHaveAttribute('aria-pressed', 'true')
    await expect(page.getByTestId('legend')).toContainText('Aug')

    // grid-strength scan: 50 km ring first, then 100 km, each strong / moderate / weak
    await expect(page.getByTestId('ring-50')).toContainText(/Strong|Moderate|Weak|Poor|Critical/, { timeout: 30000 })
    await expect(page.getByTestId('ring-100')).toContainText(/Strong|Moderate|Weak|Poor|Critical/, { timeout: 30000 })
    await expect(page.getByTestId('grid-gauge')).toBeVisible()
    await expect(page.getByTestId('water-row')).toBeVisible({ timeout: 30000 })
    await expect(page.getByTestId('hospital-list').locator('li').first()).not.toContainText(/Looking/, { timeout: 30000 })
    await shot(page, '05-explorer-grid')
    await page.getByTestId('mode-water').click()
    await expect(page.getByTestId('lens-water')).toBeVisible()
    await expect(page.getByTestId('mode-water')).toHaveAttribute('aria-pressed', 'true')
    await page.waitForTimeout(500)   // let the button colour transition finish before the screenshot
    await shot(page, '04-explorer-water')

    // lock the site: a stray map click must not move it, and every page shows the locked site
    await page.getByTestId('lock-btn').click()
    const before = await page.getByTestId('site-readout').textContent()
    await page.locator('.leaflet-container').click({ position: { x: 300, y: 300 } })
    await expect(page.getByTestId('site-readout')).toHaveText(before ?? '')
    await expect(page.getByTestId('site-readout')).toContainText('🔒')
    await page.getByTestId('lock-btn').click()

    // coordinate entry → Lokoja (Niger/Benue confluence)
    await page.getByTestId('lat-input').fill('7.8023')
    await page.getByTestId('lng-input').fill('6.7333')
    await page.getByTestId('go-btn').click()
    await expect(page.locator('.gr-appbar-center .gr-readout').first()).toContainText('7.80°N')
    await expect(page.getByTestId('water-row')).toContainText(/Niger/, { timeout: 25000 })
    await shot(page, '07-explorer-lokoja-water')

    // place search (offline fallback returns Nigerian capitals)
    await page.getByTestId('place-search').fill('Kano')
    await expect(page.locator('.gr-search-item').first()).toBeVisible({ timeout: 15000 })
    await page.locator('.gr-search-item').first().click()
    await expect(page.locator('.gr-appbar-center .gr-readout').first()).toContainText('12.0')

    await page.getByTestId('continue-facility').click()

    // ── Facility ─────────────────────────────────────────────────────────
    await expect(page).toHaveURL(/\/facility/)
    await expect(page.getByTestId('load-statement')).toContainText(/needs about/, { timeout: 20000 })
    await page.getByTestId('hospital-filter').fill('Aminu Kano')
    await page.getByTestId('featured-list').locator('li').first().click()
    await expect(page.getByTestId('facility-name')).toHaveValue(/Aminu Kano/)
    await expect(page.getByTestId('facility-type')).toHaveValue('hospital_tertiary')
    await expect(page.getByTestId('load-statement')).toContainText(/Aminu Kano/, { timeout: 20000 })
    await page.getByTestId('backup-hours').locator('button', { hasText: '12 h' }).click()
    await page.getByTestId('tab-equipment').click()
    await page.getByTestId('gen-kva').fill('1000')
    await page.getByTestId('roof').fill('6000')
    await page.getByTestId('land').fill('20000')
    await page.getByTestId('tab-priority').click()
    await page.getByTestId('priority').locator('button', { hasText: 'Balanced' }).click()
    await shot(page, '08-facility')
    await page.getByTestId('run-assessment').click()

    // ── Recommendation ───────────────────────────────────────────────────
    await expect(page).toHaveURL(/\/recommendation/, { timeout: 60000 })
    await expect(page.getByTestId('recommended-name')).toContainText(/UPS/)
    await expect(page.getByTestId('investment-case')).toContainText(/Invest/)
    await expect(page.getByTestId('reasons').locator('.gr-reason').first()).toBeVisible()
    await expect(page.getByTestId('sizing')).toContainText(/kVA/)
    await expect(page.getByTestId('ranked').locator('.gr-rank-card')).toHaveCount(5)
    await page.getByTestId('tab-agent').click()
    await expect(page.getByTestId('agent-panel')).toBeVisible()
    await expect(page.getByTestId('agent-step-classify')).toContainText(/Classify/)
    await expect(page.getByTestId('stress-tests').locator('tbody tr')).toHaveCount(4)
    await expect(page.getByTestId('affordability')).toContainText(/Concessional/)
    await shot(page, '09-recommendation')
    await shot(page, '09b-agent')
    await page.getByTestId('tab-money').click()
    await shot(page, '09c-affordability')
    await shot(page, '10-recommendation-investment')

    // ── Compare ──────────────────────────────────────────────────────────
    await page.goto('/compare')
    await expect(page.getByTestId('compare-table').locator('tbody tr')).toHaveCount(8)
    await page.getByTestId('compare-table').locator('tbody tr').nth(0).locator('input[type=checkbox]').check()
    await page.getByTestId('compare-table').locator('tbody tr').nth(1).locator('input[type=checkbox]').check()
    await page.getByTestId('tab-profiles').click()
    await expect(page.locator('.gr-radar').first()).toBeVisible()
    await shot(page, '11-compare')
    await page.screenshot({ path: 'e2e-results/screens/18-compare-full.png', fullPage: true })

    // ── Costs ────────────────────────────────────────────────────────────
    await page.goto('/costs')
    await expect(page.getByTestId('costs-page')).toContainText(/Saved over 15 years/)
    await shot(page, '12b-costs-with-vs-without')
    await page.getByTestId('tab-split').click()
    await expect(page.getByTestId('cost-table').locator('tbody tr').first()).toBeVisible()
    await expect(page.locator('.recharts-pie')).toBeVisible()
    await shot(page, '12-costs')
    await page.screenshot({ path: 'e2e-results/screens/19-costs-full.png', fullPage: true })

    // ── Simulation (WebGL) ───────────────────────────────────────────────
    await page.goto('/simulation')
    await expect(page.locator('canvas')).toBeVisible({ timeout: 30000 })
    await expect(page.getByTestId('hud')).toContainText(/\d\d:\d\d (grid on|no grid|outage)/)
    await page.getByTestId('play-btn').click()   // pause
    await page.getByTestId('time-slider').fill('20')
    await expect(page.getByTestId('hud')).toContainText(/20:00/)
    await expect(page.getByTestId('best-name')).not.toHaveText('—')
    await expect(page.getByTestId('grid-outages')).toContainText(/h off a day/)
    await expect(page.locator('.recharts-area').first()).toBeVisible()
    await page.waitForTimeout(1500)
    await shot(page, '13-simulation')
    await page.getByTestId('time-slider').fill('12')
    await expect(page.getByTestId('hud')).toContainText(/12:00/)
    await page.waitForTimeout(800)
    await shot(page, '16-sim-day')
    await page.getByTestId('time-slider').fill('22')
    await expect(page.getByTestId('hud')).toContainText(/22:00/)
    await page.waitForTimeout(800)
    await shot(page, '17-sim-night')

    // ── Learn ────────────────────────────────────────────────────────────
    await page.goto('/learn')
    await expect(page.getByTestId('tech-hydrogen')).toBeAttached()
    await expect(page.getByTestId('tech-pumped_hydro')).toBeAttached()
    await expect(page.locator('[data-testid^="tech-"]')).toHaveCount(15)
    await expect(page.getByTestId('providers-table').locator('tbody tr')).toHaveCount(7)
    await shot(page, '14-learn')

    // ── Report ───────────────────────────────────────────────────────────
    await page.goto('/report')
    await expect(page.getByTestId('report-page')).toContainText(/Executive summary/)
    await expect(page.getByTestId('report-page')).toContainText(/Investment case/)
    const [download] = await Promise.all([page.waitForEvent('download'), page.getByTestId('download-html').click()])
    expect(download.suggestedFilename()).toMatch(/GridRescue_.*\.html/)
    await shot(page, '15-report')
  })

  test('hospital → outage → simulation shows how the outage is avoided', async ({ page }) => {
    await page.goto('/explorer?lat=9.0765&lng=7.3986')
    await expect(page.getByTestId('ring-100')).toContainText(/Strong|Moderate|Weak|Poor|Critical/, { timeout: 30000 })
    const first = page.getByTestId('hospital-list').locator('li').first()
    await expect(first).not.toContainText(/Looking/, { timeout: 30000 })
    await first.click()
    // step 2: the assumptions and a daily power-use band
    await expect(page.getByTestId('sizing-estimate')).toContainText(/kWh/, { timeout: 15000 })
    await page.getByTestId('usage-l').click()
    await expect(page.getByTestId('sizing-estimate')).toContainText(/2,250 kWh/)
    await page.getByTestId('outage-collapse').click()
    await shot(page, '06-explorer-hospital-outage')
    await page.getByTestId('simulate-outage').click()
    await expect(page).toHaveURL(/\/simulation/, { timeout: 120000 })
    await expect(page.getByTestId('outage-verdict')).toContainText(/National grid collapse/)
    await expect(page.getByTestId('simulation-page')).toContainText(/2,250 kWh/)
    await expect(page.getByTestId('outage-verdict')).toContainText(/avoided/)
    await expect(page.getByTestId('device-type')).toContainText(/Recommended Backup Device/)
    await expect(page.getByTestId('grid-outages')).toContainText(/collapses in 2024/)
    await page.waitForTimeout(1200)
    await shot(page, '13b-simulation-grid-collapse')
    await expect(page.getByTestId('price-now')).toContainText(/₦[\d,]+\/kWh/)
    await page.getByTestId('chart-cost').click()
    await expect(page.getByTestId('best-card')).toContainText(/saved today/)
    await page.waitForTimeout(600)
    await shot(page, '13e-simulation-cost-view')
    await page.getByTestId('chart-power').click()
    await page.getByTestId('outage-select').selectOption('evening')
    await expect(page.getByTestId('outage-verdict')).toContainText(/Evening load-shedding/, { timeout: 120000 })
    await shot(page, '13c-simulation-evening')
    // supply choice: an off-grid hospital must never get a grid-charged backup device, and the screen stays one page
    await page.getByTestId('supply-btn').click()
    await page.getByTestId('supply-grid').uncheck()
    await expect(page.getByTestId('supply-btn')).not.toContainText('Grid', { timeout: 120000 })
    await expect(page.getByTestId('best-name')).not.toContainText(/grid-charged/)
    await page.getByTestId('supply-wind').uncheck()
    await page.getByTestId('supply-btn').click()
    expect(await page.evaluate(() => document.documentElement.scrollHeight <= window.innerHeight + 1)).toBe(true)
    await page.waitForTimeout(1200)
    await shot(page, '13d-simulation-solar-only')
  })

  test('result pages show an empty state without an assessment; Simulate runs the selected location instead', async ({ page }) => {
    await page.goto('/recommendation')
    await expect(page.getByTestId('empty-assessment')).toBeVisible()
    await page.goto('/simulation')
    await expect(page.getByTestId('simulation-page')).toBeVisible({ timeout: 180000 })
    await expect(page.getByTestId('sim-location-tag')).toBeVisible()
  })

  test('shareable explorer link restores site and mode', async ({ page }) => {
    await page.goto('/explorer?lat=6.5244&lng=3.3792&mode=wind')
    await expect(page.getByTestId('lens-wind')).toBeVisible()
    await expect(page.locator('.gr-appbar-center .gr-readout').first()).toContainText('6.52°N, 3.38°E')
  })
})
